// ---------- Data (stored only on this phone, in a local Room/SQLite database) ----------

@Entity(tableName = "tickets")
data class Ticket(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val firstName: String = "",
    val lastName: String = "",
    val venueType: String = "Concert",
    val ticketType: String = "Standard",
    val venue: String = "",
    val location: String = "",
    val date: String = "",
    val time: String = "",
    val seat: String = "",
    val price: Double = 0.0,
    val status: String = "Active",
    val notes: String = "",
    // Scanned from a real ticket, or generated by this app. Used by Scan to check a ticket.
    @ColumnInfo(defaultValue = "''") val code: String = ""
)

@Dao
interface TicketDao {
    @Query("SELECT * FROM tickets ORDER BY date, time")
    fun all(): Flow<List<Ticket>>
    @Insert suspend fun insert(t: Ticket): Long
    @Update suspend fun update(t: Ticket)
    @Delete suspend fun delete(t: Ticket)
}

@Database(entities = [Ticket::class], version = 2, exportSchema = false)
abstract class AppDb : RoomDatabase() {
    abstract fun dao(): TicketDao
    companion object {
        @Volatile private var instance: AppDb? = null
        fun get(c: android.content.Context): AppDb = instance ?: synchronized(this) {
            instance ?: Room.databaseBuilder(c.applicationContext, AppDb::class.java, "tickets.db")
                .addMigrations(MIGRATION_1_2).build().also { instance = it }
        }
    }
}

val MIGRATION_1_2 = object : Migration(1, 2) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE tickets ADD COLUMN code TEXT NOT NULL DEFAULT ''")
    }
}

class TicketVm(app: Application) : AndroidViewModel(app) {
    private val dao = AppDb.get(app).dao()
    val tickets = dao.all().stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), emptyList())
    fun save(t: Ticket) { viewModelScope.launch { if (t.id == 0L) dao.insert(t) else dao.update(t) } }
    fun saveAll(l: List<Ticket>) { viewModelScope.launch { l.forEach { dao.insert(it.copy(id = 0)) } } }
    fun delete(t: Ticket) { viewModelScope.launch { dao.delete(t) } }
}

val VENUE_TYPES = listOf("Concert", "Theater", "Sports", "Conference", "Cinema", "Festival", "Exhibition", "Comedy Show", "Other")
val TICKET_TYPES = listOf("Standard", "VIP", "Early Bird", "Group", "Student", "Season Pass", "Backstage", "Other")
val STATUSES = listOf("Active", "Used", "Cancelled", "Refunded")

private fun money(d: Double) = "\$" + "%.2f".format(d)

private fun Ticket.searchText() = listOf(firstName, lastName, venueType, ticketType, venue,
    location, date, time, seat, status, notes).joinToString(" ")

private fun toCsv(list: List<Ticket>): String {
    val head = listOf("First Name", "Last Name", "Venue Type", "Ticket Type", "Venue / Event",
        "Location", "Date", "Time", "Seat / Section", "Price", "Status", "Notes", "Code")
    fun q(s: String): String {
        // A leading = + - @ could run as a formula in Excel, so neutralise it.
        val safe = if (s.isNotEmpty() && s[0] in "=+-@") "'$s" else s
        return "\"" + safe.replace("\"", "\"\"") + "\""
    }
    val rows = list.map { t ->
        listOf(t.firstName, t.lastName, t.venueType, t.ticketType, t.venue, t.location, t.date,
            t.time, t.seat, "%.2f".format(t.price), t.status, t.notes, t.code).joinToString(",") { q(it) }
    }
    return (listOf(head.joinToString(",")) + rows).joinToString("\r\n")
}

private fun newCode(existing: List<Ticket>): String {
    val used = existing.map { it.code }.toSet()
    while (true) {
        val c = "TM-" + java.util.UUID.randomUUID().toString().replace("-", "").take(12).uppercase()
        if (c !in used) return c
    }
}

/** Draws a QR code or a Code 128 barcode. Throws if the text cannot be encoded. */
private fun makeBitmap(text: String, qr: Boolean): Bitmap {
    val m = MultiFormatWriter().encode(
        text, if (qr) BarcodeFormat.QR_CODE else BarcodeFormat.CODE_128,
        if (qr) 600 else 900, if (qr) 600 else 300)
    val px = IntArray(m.width * m.height) { i ->
        if (m[i % m.width, i / m.width]) 0xFF000000.toInt() else 0xFFFFFFFF.toInt()
    }
    return Bitmap.createBitmap(px, m.width, m.height, Bitmap.Config.ARGB_8888)
}

/** Opens Google's code scanner (needs Google Play services; no camera permission needed). */
private fun scanCode(context: Context, onResult: (String) -> Unit) {
    val options = GmsBarcodeScannerOptions.Builder().setBarcodeFormats(Barcode.FORMAT_ALL_FORMATS).build()
    GmsBarcodeScanning.getClient(context, options).startScan()
        .addOnSuccessListener { b -> b.rawValue?.let(onResult) }
        .addOnFailureListener {
            Toast.makeText(context, "Scanner unavailable. It needs Google Play services.", Toast.LENGTH_LONG).show()
        }
}

private fun parseCsv(text: String): List<List<String>> {
    val rows = mutableListOf<List<String>>()
    var row = mutableListOf<String>()
    val f = StringBuilder()
    var quoted = false
    val s = text.removePrefix("\uFEFF")
    var i = 0
    while (i < s.length) {
        val c = s[i]
        if (quoted) {
            if (c == '"') { if (i + 1 < s.length && s[i + 1] == '"') { f.append('"'); i++ } else quoted = false }
            else f.append(c)
        } else when (c) {
            '"' -> quoted = true
            ',' -> { row.add(f.toString()); f.setLength(0) }
            '\r' -> {}
            '\n' -> { row.add(f.toString()); f.setLength(0); rows.add(row); row = mutableListOf() }
            else -> f.append(c)
        }
        i++
    }
    if (f.isNotEmpty() || row.isNotEmpty()) { row.add(f.toString()); rows.add(row) }
    return rows
}

private fun dupKey(t: Ticket) = listOf(t.firstName, t.lastName, t.venue, t.date, t.time, t.seat,
    "%.2f".format(t.price), t.status).joinToString("|")

/** Reads a CSV made by Export CSV (this app or the desktop app). Returns (new tickets, skipped, invalid). */
private fun importTickets(text: String, existing: List<Ticket>): Triple<List<Ticket>, Int, Int> {
    val rows = parseCsv(text).filter { r -> r.any { it.isNotBlank() } }
    if (rows.size < 2) return Triple(emptyList(), 0, 0)
    val idx = rows[0].mapIndexed { i, h -> h.trim().lowercase() to i }.toMap()
    if ("first name" !in idx || "venue / event" !in idx) return Triple(emptyList(), 0, rows.size - 1)
    fun col(r: List<String>, name: String): String {
        val v = idx[name]?.let { r.getOrNull(it) }?.trim() ?: ""
        return if (v.length > 1 && v[0] == '\'' && v[1] in "=+-@") v.substring(1) else v
    }
    fun pick(v: String, options: List<String>, def: String) = options.firstOrNull { it.equals(v, true) } ?: def
    val have = existing.map { dupKey(it) }.toSet()
    val usedCodes = existing.map { it.code }.filter { it.isNotBlank() }.toMutableSet()
    val out = mutableListOf<Ticket>()
    var skipped = 0
    var invalid = 0
    for (r in rows.drop(1)) {
        var t = Ticket(
            firstName = col(r, "first name"), lastName = col(r, "last name"),
            venueType = pick(col(r, "venue type"), VENUE_TYPES, "Other"),
            ticketType = pick(col(r, "ticket type"), TICKET_TYPES, "Other"),
            venue = col(r, "venue / event"), location = col(r, "location"),
            date = col(r, "date"), time = col(r, "time"), seat = col(r, "seat / section"),
            price = col(r, "price").replace("$", "").replace(",", "").toDoubleOrNull() ?: 0.0,
            status = pick(col(r, "status"), STATUSES, "Active"), notes = col(r, "notes"),
            code = col(r, "code")
        )
        if (t.venue.isBlank() || (t.firstName.isBlank() && t.lastName.isBlank())) { invalid++; continue }
        if (dupKey(t) in have) { skipped++; continue }
        if (t.code.isNotBlank() && !usedCodes.add(t.code)) t = t.copy(code = "")
        out.add(t)
    }
    return Triple(out, skipped, invalid)
}

private fun describe(t: Ticket) = "${t.firstName} ${t.lastName}".trim() + "\n" +
    listOf(t.venue, t.date, t.time).filter { it.isNotBlank() }.joinToString(" · ") +
    (if (t.seat.isNotBlank()) "\n" + t.seat else "")

