}

/** Draws a QR code or a Code 128 barcode. Throws if the text cannot be encoded. */
private fun makeBitmap(text: String, qr: Boolean): Bitmap {
    val m = MultiFormatWriter().encode(
        text, if (qr) BarcodeFormat.QR_CODE else BarcodeFormat.CODE_128,
        if (qr) 600 else 900, if (qr) 600 else 300)
    val px = IntArray(m.width * m.height) { i ->
        if (m[i % m.width, i / m.width]) 0xFF000000.toInt() else 0xFFFFFFFF.toInt()
    }
    return Bitmap.createBitmap(px, m.width, m.height, Bitmap.Config.ARGB_8888)
}

/** Opens Google's code scanner (needs Google Play services; no camera permission needed). */
private fun scanCode(context: Context, onResult: (String) -> Unit) {
    val options = GmsBarcodeScannerOptions.Builder().setBarcodeFormats(Barcode.FORMAT_ALL_FORMATS).build()
    GmsBarcodeScanning.getClient(context, options).startScan()
        .addOnSuccessListener { b -> b.rawValue?.let(onResult) }
        .addOnFailureListener {
            Toast.makeText(context, "Scanner unavailable. It needs Google Play services.", Toast.LENGTH_LONG).show()
        }
}

private fun parseCsv(text: String): List<List<String>> {
    val rows = mutableListOf<List<String>>()
    var row = mutableListOf<String>()
    val f = StringBuilder()
    var quoted = false
    val s = text.removePrefix("\uFEFF")
    var i = 0
    while (i < s.length) {
        val c = s[i]
        if (quoted) {
            if (c == '"') { if (i + 1 < s.length && s[i + 1] == '"') { f.append('"'); i++ } else quoted = false }
            else f.append(c)
        } else when (c) {
            '"' -> quoted = true
            ',' -> { row.add(f.toString()); f.setLength(0) }
            '\r' -> {}
            '\n' -> { row.add(f.toString()); f.setLength(0); rows.add(row); row = mutableListOf() }
            else -> f.append(c)
        }
        i++
    }
    if (f.isNotEmpty() || row.isNotEmpty()) { row.add(f.toString()); rows.add(row) }
    return rows
}

private fun dupKey(t: Ticket) = listOf(t.firstName, t.lastName, t.venue, t.date, t.time, t.seat,
    "%.2f".format(t.price), t.status).joinToString("|")

/** Reads a CSV made by Export CSV (this app or the desktop app). Returns (new tickets, skipped, invalid). */
private fun importTickets(text: String, existing: List<Ticket>): Triple<List<Ticket>, Int, Int> {
    val rows = parseCsv(text).filter { r -> r.any { it.isNotBlank() } }
    if (rows.size < 2) return Triple(emptyList(), 0, 0)
    val idx = rows[0].mapIndexed { i, h -> h.trim().lowercase() to i }.toMap()
    if ("first name" !in idx || "venue / event" !in idx) return Triple(emptyList(), 0, rows.size - 1)
    fun col(r: List<String>, name: String): String {
        val v = idx[name]?.let { r.getOrNull(it) }?.trim() ?: ""
        return if (v.length > 1 && v[0] == '\'' && v[1] in "=+-@") v.substring(1) else v
    }
    fun pick(v: String, options: List<String>, def: String) = options.firstOrNull { it.equals(v, true) } ?: def
    val have = existing.map { dupKey(it) }.toSet()
    val usedCodes = existing.map { it.code }.filter { it.isNotBlank() }.toMutableSet()
    val out = mutableListOf<Ticket>()
    var skipped = 0
    var invalid = 0
    for (r in rows.drop(1)) {
        var t = Ticket(
            firstName = col(r, "first name"), lastName = col(r, "last name"),
            venueType = pick(col(r, "venue type"), VENUE_TYPES, "Other"),
            ticketType = pick(col(r, "ticket type"), TICKET_TYPES, "Other"),
            venue = col(r, "venue / event"), location = col(r, "location"),
            date = col(r, "date"), time = col(r, "time"), seat = col(r, "seat / section"),
            price = col(r, "price").replace("$", "").replace(",", "").toDoubleOrNull() ?: 0.0,
            status = pick(col(r, "status"), STATUSES, "Active"), notes = col(r, "notes"),
            code = col(r, "code")
        )
        if (t.venue.isBlank() || (t.firstName.isBlank() && t.lastName.isBlank())) { invalid++; continue }
        if (dupKey(t) in have) { skipped++; continue }
        if (t.code.isNotBlank() && !usedCodes.add(t.code)) t = t.copy(code = "")
        out.add(t)
    }
    return Triple(out, skipped, invalid)
}

private fun describe(t: Ticket) = "${t.firstName} ${t.lastName}".trim() + "\n" +
    listOf(t.venue, t.date, t.time).filter { it.isNotBlank() }.joinToString(" · ") +
    (if (t.seat.isNotBlank()) "\n" + t.seat else "")

