private fun toCsv(list: List<Ticket>): String {
    val head = listOf("First Name", "Last Name", "Venue Type", "Ticket Type", "Venue / Event",
        "Location", "Date", "Time", "Seat / Section", "Price", "Status", "Notes", "Code")
    fun q(s: String): String {
        // A leading = + - @ could run as a formula in Excel, so neutralise it.
        val safe = if (s.isNotEmpty() && s[0] in "=+-@") "'$s" else s
        return "\"" + safe.replace("\"", "\"\"") + "\""
    }
    val rows = list.map { t ->
        listOf(t.firstName, t.lastName, t.venueType, t.ticketType, t.venue, t.location, t.date,
            t.time, t.seat, "%.2f".format(t.price), t.status, t.notes, t.code).joinToString(",") { q(it) }
    }
    return (listOf(head.joinToString(",")) + rows).joinToString("\r\n")
}

private class SignInRequired(message: String) : Exception(message)

/**
 * Sign-in with Google using the user's own OAuth client (type "Desktop app").
 * The user enters the Client ID and secret in the app. Sign-in happens in the web browser:
 * Google sends the browser back to a temporary address on this phone (127.0.0.1) that only
 * this app listens on. Credentials and tokens are kept in this app's private storage.
 */
private object GoogleAuth {
    private const val SCOPE = "https://www.googleapis.com/auth/drive.appdata"
    private const val AUTH_URL = "https://accounts.google.com/o/oauth2/v2/auth"
    private const val TOKEN_URL = "https://oauth2.googleapis.com/token"

    private fun post(url: String, form: Map<String, String>): Pair<Int, JSONObject> {
        val body = form.entries.joinToString("&") {
            URLEncoder.encode(it.key, "UTF-8") + "=" + URLEncoder.encode(it.value, "UTF-8")
        }
        val c = URL(url).openConnection() as HttpURLConnection
        c.requestMethod = "POST"
        c.doOutput = true
        c.connectTimeout = 20000
        c.readTimeout = 30000
        c.setRequestProperty("Content-Type", "application/x-www-form-urlencoded")
        c.outputStream.use { it.write(body.toByteArray()) }
        val code = c.responseCode
        val text = (if (code in 200..299) c.inputStream else c.errorStream)?.bufferedReader()?.use { it.readText() } ?: "{}"
        return code to (try { JSONObject(text) } catch (e: Exception) { JSONObject() })
    }

    private fun describe(j: JSONObject, code: Int): String {
        val err = j.optString("error")
        return if (err == "invalid_client" || err == "unauthorized_client")
            "Google did not accept the Client ID or secret. Check that the OAuth client type is \"Desktop app\" and that you copied both values exactly."
        else j.optString("error_description", "").ifEmpty { "Google returned error $code" }
    }

    fun clientId(p: SharedPreferences) = p.getString("client_id", "").orEmpty()
    fun clientSecret(p: SharedPreferences) = p.getString("client_secret", "").orEmpty()
    fun configured(p: SharedPreferences) = clientId(p).isNotBlank() && clientSecret(p).isNotBlank()
    fun signedIn(p: SharedPreferences) = p.getString("refresh_token", "").orEmpty().isNotEmpty()

    fun saveClient(p: SharedPreferences, id: String, secret: String) {
        val changed = id != clientId(p) || secret != clientSecret(p)
        val e = p.edit().putString("client_id", id).putString("client_secret", secret)
        if (changed) e.remove("refresh_token").remove("access_token").remove("expires_at")
        e.apply()
    }

    fun signOut(p: SharedPreferences) {
        p.edit().remove("refresh_token").remove("access_token").remove("expires_at").apply()
    }

    private fun b64(bytes: ByteArray) = Base64.encodeToString(bytes, Base64.URL_SAFE or Base64.NO_PADDING or Base64.NO_WRAP)

    /**
     * Opens the web browser (via openBrowser) and waits until the user has signed in and Google
     * has sent the browser back to this app. Cancel by cancelling the coroutine.
     */
    suspend fun webSignIn(p: SharedPreferences, openBrowser: (String) -> Unit) {
        val rnd = SecureRandom()
        val verifier = b64(ByteArray(48).also { rnd.nextBytes(it) })
        val challenge = b64(MessageDigest.getInstance("SHA-256").digest(verifier.toByteArray()))
        val state = b64(ByteArray(16).also { rnd.nextBytes(it) })
        val server = ServerSocket(0, 5, InetAddress.getByName("127.0.0.1"))   // this phone only
        try {
            val redirect = "http://127.0.0.1:${server.localPort}"
            val params = mapOf(
                "response_type" to "code", "client_id" to clientId(p), "redirect_uri" to redirect,
                "scope" to SCOPE, "state" to state, "code_challenge" to challenge,
                "code_challenge_method" to "S256", "access_type" to "offline", "prompt" to "consent")
            openBrowser(AUTH_URL + "?" + params.entries.joinToString("&") {
                it.key + "=" + URLEncoder.encode(it.value, "UTF-8")
            })
            val result = withContext(Dispatchers.IO) { waitForRedirect(server) }
            if (result.getQueryParameter("state") != state) throw IOException("Sign-in failed (the response did not match the request).")
            val code = result.getQueryParameter("code")
            if (result.getQueryParameter("error") != null || code == null) throw IOException("Sign-in was cancelled or not allowed.")
            val (status, j) = withContext(Dispatchers.IO) {
                post(TOKEN_URL, mapOf(
                    "code" to code, "client_id" to clientId(p), "client_secret" to clientSecret(p),
                    "redirect_uri" to redirect, "grant_type" to "authorization_code", "code_verifier" to verifier))
            }
            if (status !in 200..299) throw IOException(describe(j, status))
            if (!j.has("refresh_token")) throw IOException("Google did not return a sign-in token. Remove the app's access at myaccount.google.com/permissions and try again.")
            store(p, j)
        } finally {
            server.close()
        }
    }

    private fun CoroutineScope.waitForRedirect(server: ServerSocket): Uri {
        server.soTimeout = 1000
        val deadline = System.currentTimeMillis() + 5 * 60 * 1000L
        while (System.currentTimeMillis() < deadline) {
            ensureActive()                               // stops quickly when the user cancels
            val socket = try { server.accept() } catch (e: SocketTimeoutException) { continue }
            socket.use { sock ->
                sock.soTimeout = 3000
                val line = try { sock.getInputStream().bufferedReader().readLine() } catch (e: Exception) { null } ?: return@use
                val path = line.split(" ").getOrNull(1) ?: return@use
                val uri = Uri.parse("http://127.0.0.1$path")
                val page = "<html><body style=\"font-family:sans-serif\"><h2>Ticket Manager</h2><p>You can close this tab and return to the app.</p></body></html>"
                val out = "HTTP/1.1 200 OK\r\nContent-Type: text/html; charset=utf-8\r\nContent-Length: ${page.toByteArray().size}\r\nConnection: close\r\n\r\n$page"
                sock.getOutputStream().apply { write(out.toByteArray()); flush() }
                if (uri.getQueryParameter("code") != null || uri.getQueryParameter("error") != null) return uri
            }
        }
        throw IOException("Sign-in timed out. Please try again.")
    }

    private fun store(p: SharedPreferences, j: JSONObject) {
        p.edit()
            .putString("refresh_token", j.optString("refresh_token", p.getString("refresh_token", "").orEmpty()))
            .putString("access_token", j.getString("access_token"))
            .putLong("expires_at", System.currentTimeMillis() + j.optInt("expires_in", 3600) * 1000L)
            .apply()
    }

    /** Blocking; call from IO. Refreshes the access token when it has expired. */
    fun accessToken(p: SharedPreferences): String {
        if (!signedIn(p)) throw SignInRequired("Please sign in with Google first.")
        val at = p.getString("access_token", "").orEmpty()
        if (at.isNotEmpty() && p.getLong("expires_at", 0) - 60_000 > System.currentTimeMillis()) return at
        val (code, j) = post(TOKEN_URL, mapOf(
            "client_id" to clientId(p), "client_secret" to clientSecret(p),
            "refresh_token" to p.getString("refresh_token", "").orEmpty(), "grant_type" to "refresh_token"))
        if (code !in 200..299) {
            if (j.optString("error") == "invalid_grant") {
                signOut(p)
                throw SignInRequired("Your Google sign-in expired. Please sign in again.")
            }
            throw IOException(describe(j, code))
        }
        store(p, j)
        return j.getString("access_token")
    }
}

/** Google Drive's hidden app-data folder: this app can only see files it created itself. */
private object DriveApi {
    private const val NAME = "ticket-manager-sync.json"
    private const val API = "https://www.googleapis.com/drive/v3"
    private const val UPLOAD = "https://www.googleapis.com/upload/drive/v3"

    private fun call(method: String, url: String, token: String, body: ByteArray? = null, type: String? = null): String {
        val c = URL(url).openConnection() as HttpURLConnection
        // HttpURLConnection has no PATCH; Google accepts POST with this override header.
        c.requestMethod = if (method == "PATCH") "POST" else method
        if (method == "PATCH") c.setRequestProperty("X-HTTP-Method-Override", "PATCH")
        c.setRequestProperty("Authorization", "Bearer $token")
        c.connectTimeout = 20000
        c.readTimeout = 30000
        if (body != null) {
            c.doOutput = true
            c.setRequestProperty("Content-Type", type)
            c.outputStream.use { it.write(body) }
        }
        val code = c.responseCode
        val text = (if (code in 200..299) c.inputStream else c.errorStream)?.bufferedReader()?.use { it.readText() } ?: ""
        if (code !in 200..299) throw IOException("Google Drive error $code")
        if (text.length > 20_000_000) throw IOException("The sync data is too large")
        return text
    }

    private fun findId(token: String): String? {
        val q = URLEncoder.encode("name = '$NAME' and trashed = false", "UTF-8")
        val r = call("GET", "$API/files?spaces=appDataFolder&pageSize=10&fields=files(id)&q=$q", token)
        val files = JSONObject(r).getJSONArray("files")
        return if (files.length() > 0) files.getJSONObject(0).getString("id") else null
    }

    fun download(token: String): String? = findId(token)?.let { call("GET", "$API/files/$it?alt=media", token) }

    fun upload(token: String, json: String) {
        val data = json.toByteArray()
        val id = findId(token)
        if (id != null) {
            call("PATCH", "$UPLOAD/files/$id?uploadType=media", token, data, "application/json")
        } else {
            val b = "tm" + java.util.UUID.randomUUID().toString().replace("-", "")
            val meta = JSONObject().put("name", NAME).put("parents", JSONArray().put("appDataFolder")).toString()
            val body = ("--$b\r\nContent-Type: application/json; charset=UTF-8\r\n\r\n$meta\r\n" +
                "--$b\r\nContent-Type: application/json\r\n\r\n").toByteArray() + data + "\r\n--$b--".toByteArray()
            call("POST", "$UPLOAD/files?uploadType=multipart", token, body, "multipart/related; boundary=$b")
        }
    }
}

private fun parseSync(text: String): List<Ticket> {
    val root = JSONObject(text)
    if (root.optInt("version", 1) > 1) throw IOException("This sync file was made by a newer version of the app")
    val arr = root.getJSONArray("tickets")
    return (0 until arr.length()).mapNotNull { i ->
        val o = arr.getJSONObject(i)
        val uid = o.optString("uid", "").trim()
        if (uid.isEmpty()) null else Ticket(
            uid = uid, firstName = o.optString("first_name", ""), lastName = o.optString("last_name", ""),
            venueType = o.optString("venue_type", "Other"), ticketType = o.optString("ticket_type", "Other"),
            venue = o.optString("venue_name", ""), location = o.optString("location", ""),
            date = o.optString("date", ""), time = o.optString("time", ""), seat = o.optString("seat", ""),
            price = o.optDouble("price", 0.0), status = o.optString("status", "Active"),
            notes = o.optString("notes", ""), code = o.optString("code", ""),
            updatedAt = o.optLong("updated_at", 0), deleted = o.optBoolean("deleted", false)
        )
    }
}

private fun toSyncJson(list: List<Ticket>): String {
    val arr = JSONArray()
    list.forEach { t ->
        arr.put(JSONObject().apply {
            put("uid", t.uid); put("first_name", t.firstName); put("last_name", t.lastName)
            put("venue_type", t.venueType); put("ticket_type", t.ticketType); put("venue_name", t.venue)
            put("location", t.location); put("date", t.date); put("time", t.time); put("seat", t.seat)
            put("price", t.price); put("status", t.status); put("notes", t.notes); put("code", t.code)
            put("updated_at", t.updatedAt); put("deleted", t.deleted)
        })
    }
    return JSONObject().put("version", 1).put("tickets", arr).toString(1)
}

