@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AppScreen(vm: TicketVm = viewModel()) {
    val context = LocalContext.current
    val all by vm.tickets.collectAsState()
    var query by remember { mutableStateOf("") }
    var selected by remember { mutableStateOf("All Venues") }
    var form by remember { mutableStateOf<Ticket?>(null) }
    var toDelete by remember { mutableStateOf<Ticket?>(null) }
    var codeFor by remember { mutableStateOf<Ticket?>(null) }
    var scanRaw by remember { mutableStateOf<String?>(null) }
    var menu by remember { mutableStateOf(false) }

    val venues = listOf("All Venues") + all.map { it.venue }.filter { it.isNotBlank() }.distinct().sorted()
    val tab = if (selected in venues) selected else "All Venues"
    val shown = all.filter { t ->
        (tab == "All Venues" || t.venue == tab) &&
            (query.isBlank() || t.searchText().contains(query.trim(), ignoreCase = true))
    }
    val total = shown.filter { it.status != "Cancelled" && it.status != "Refunded" }.sumOf { it.price }

    val saver = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("text/csv")) { uri: Uri? ->
        uri?.let { u ->
            context.contentResolver.openOutputStream(u)?.use { it.write(toCsv(shown).toByteArray()) }
        }
    }

    val importer = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri: Uri? ->
        uri?.let { u ->
            val text = try {
                context.contentResolver.openInputStream(u)?.bufferedReader()?.use { it.readText() }
            } catch (e: Exception) { null }
            if (text == null || text.length > 5_000_000) {
                Toast.makeText(context, "Could not read that file (maximum 5 MB).", Toast.LENGTH_LONG).show()
            } else {
                val (list, skipped, invalid) = importTickets(text, all)
                vm.saveAll(list)
                Toast.makeText(context, "Imported ${list.size}. Skipped $skipped already here. Ignored $invalid invalid rows.", Toast.LENGTH_LONG).show()
            }
        }
    }

    val prefs = remember { context.getSharedPreferences("sync", Context.MODE_PRIVATE) }
    var syncUri by remember { mutableStateOf(prefs.getString("sync_uri", null)) }
    fun runSync(u: Uri) {
        Toast.makeText(context, "Syncing…", Toast.LENGTH_SHORT).show()
        vm.sync(u) { Toast.makeText(context, it, Toast.LENGTH_LONG).show() }
    }
    fun useSyncFile(u: Uri) {
        try {
            context.contentResolver.takePersistableUriPermission(
                u, Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_GRANT_WRITE_URI_PERMISSION)
        } catch (e: Exception) { /* some providers do not allow it; sync may ask again later */ }
        prefs.edit().putString("sync_uri", u.toString()).apply()
        syncUri = u.toString()
        runSync(u)
    }
    fun runDriveSync(token: String) {
        Toast.makeText(context, "Syncing…", Toast.LENGTH_SHORT).show()
        vm.syncDrive(token) { Toast.makeText(context, it, Toast.LENGTH_LONG).show() }
    }
    val scope = rememberCoroutineScope()
    val gprefs = remember { context.getSharedPreferences("google", Context.MODE_PRIVATE) }
    var showCreds by remember { mutableStateOf(false) }
    var signInUrl by remember { mutableStateOf<String?>(null) }
    var signInJob by remember { mutableStateOf<Job?>(null) }
    fun toast(m: String) = Toast.makeText(context, m, Toast.LENGTH_LONG).show()
    fun driveSync() {
        scope.launch {
            try {
                val token = withContext(Dispatchers.IO) { GoogleAuth.accessToken(gprefs) }
                runDriveSync(token)
            } catch (e: SignInRequired) {
                toast(e.message ?: "Please sign in again.")
            } catch (e: Exception) {
                toast("Google sync failed: ${e.message}")
            }
        }
    }
    fun googleSync() {
        if (!GoogleAuth.configured(gprefs)) { showCreds = true; return }
        if (GoogleAuth.signedIn(gprefs)) { driveSync(); return }
        signInJob = scope.launch {
            try {
                GoogleAuth.webSignIn(gprefs) { url ->
                    signInUrl = url
                    context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(url)))
                }
                signInUrl = null
                driveSync()
            } catch (e: CancellationException) {
                signInUrl = null
                throw e
            } catch (e: Exception) {
                signInUrl = null
                toast(e.message ?: "Google sign-in failed")
            }
        }
    }
    val syncCreator = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/json")) { u: Uri? -> u?.let { useSyncFile(it) } }
    val syncOpener = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { u: Uri? -> u?.let { useSyncFile(it) } }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Ticket Manager") },
                actions = {
                    TextButton(onClick = { scanCode(context) { scanRaw = it } }) { Text("Scan") }
                    Box {
                        TextButton(onClick = { menu = true }) { Text("More") }
                        DropdownMenu(expanded = menu, onDismissRequest = { menu = false }) {
                            DropdownMenuItem(text = { Text("Import CSV") }, onClick = {
                                menu = false
                                importer.launch(arrayOf("text/*", "application/csv", "application/vnd.ms-excel"))
                            })
                            DropdownMenuItem(text = { Text("Export CSV") }, onClick = {
                                menu = false
                                saver.launch("tickets.csv")
                            })
                            DropdownMenuItem(text = { Text("Sync with Google") }, onClick = {
                                menu = false
                                googleSync()
                            })
                            DropdownMenuItem(text = { Text("Google credentials") }, onClick = {
                                menu = false
                                showCreds = true
                            })
                            if (syncUri == null) {
                                DropdownMenuItem(text = { Text("Sync: create new sync file") }, onClick = {
                                    menu = false
                                    syncCreator.launch("ticket-manager-sync.json")
                                })
                                DropdownMenuItem(text = { Text("Sync: use existing sync file") }, onClick = {
                                    menu = false
                                    syncOpener.launch(arrayOf("*/*"))
                                })
                            } else {
                                DropdownMenuItem(text = { Text("Sync now") }, onClick = {
                                    menu = false
                                    runSync(Uri.parse(syncUri!!))
                                })
                                DropdownMenuItem(text = { Text("Stop syncing") }, onClick = {
                                    menu = false
                                    prefs.edit().remove("sync_uri").apply()
                                    syncUri = null
                                })
                            }
                        }
                    }
                }
            )
        },
        floatingActionButton = {
            ExtendedFloatingActionButton(onClick = { form = Ticket() }) { Text("+ Add ticket") }
        },
        bottomBar = {
            Surface(Modifier.fillMaxWidth(), tonalElevation = 3.dp) {
                Text(
                    "${shown.size} tickets in \"$tab\"  •  Active value: ${money(total)}",
                    Modifier.navigationBarsPadding().padding(12.dp),
                    style = MaterialTheme.typography.bodySmall
                )
            }
        }
    ) { pad ->
        Column(Modifier.padding(pad)) {
            OutlinedTextField(
                value = query, onValueChange = { query = it },
                label = { Text("Search tickets") }, singleLine = true,
                modifier = Modifier.fillMaxWidth().padding(horizontal = 12.dp, vertical = 8.dp)
            )
            ScrollableTabRow(selectedTabIndex = venues.indexOf(tab), edgePadding = 8.dp) {
                venues.forEach { v -> Tab(selected = v == tab, onClick = { selected = v }, text = { Text(v) }) }
            }
            if (shown.isEmpty()) {
                Text("No tickets to show. Tap \"+ Add ticket\" to create one.",
                    Modifier.padding(24.dp), color = MaterialTheme.colorScheme.onSurfaceVariant)
            }
            LazyColumn(
                contentPadding = PaddingValues(12.dp, 12.dp, 12.dp, 96.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                items(shown, key = { it.id }) { t ->
                    TicketCard(t,
                        onEdit = { form = t },
                        onDuplicate = { form = t.copy(id = 0, code = "", uid = "") },
                        onCode = {
                            val tt = if (t.code.isBlank()) t.copy(code = newCode(all)).also { vm.save(it) } else t
                            codeFor = tt
                        },
                        onDelete = { toDelete = t })
                }
            }
        }
    }

    form?.let { f ->
        TicketForm(f, onCancel = { form = null }, onSave = { vm.save(it); form = null })
    }
    if (showCreds) {
        CredentialsDialog(gprefs, onClose = { showCreds = false },
            onSaved = { showCreds = false; googleSync() })
    }
    signInUrl?.let { url ->
        AlertDialog(
            onDismissRequest = {},
            title = { Text("Sign in with Google") },
            text = { Text("Your web browser opened so you can sign in to Google and allow access. When you are done, come back to this app. It finishes by itself.") },
            confirmButton = {
                TextButton(onClick = { context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(url))) }) { Text("Open browser again") }
            },
            dismissButton = { TextButton(onClick = { signInJob?.cancel(); signInUrl = null }) { Text("Cancel") } }
        )
    }
    codeFor?.let { t ->
        var qr by remember { mutableStateOf(true) }
        val bmp = remember(t.code, qr) { runCatching { makeBitmap(t.code, qr) }.getOrNull() }
        AlertDialog(
            onDismissRequest = { codeFor = null },
            title = { Text("Code for " + "${t.firstName} ${t.lastName}".trim()) },
            text = {
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    if (bmp != null) {
                        Image(bmp.asImageBitmap(), "${if (qr) "QR code" else "Barcode"} for ticket code ${t.code}",
                            Modifier.fillMaxWidth().background(Color.White).padding(8.dp))
                    } else {
                        Text("This code cannot be drawn as a Code 128 barcode. Try the QR code.")
                    }
                    Text(t.code, Modifier.padding(top = 8.dp), fontWeight = FontWeight.SemiBold)
                    TextButton(onClick = { qr = !qr }) { Text(if (qr) "Show Code 128 barcode" else "Show QR code") }
                }
            },
            confirmButton = { TextButton(onClick = { codeFor = null }) { Text("Close") } }
        )
    }
    scanRaw?.let { raw ->
        val m = all.filter { it.code.isNotBlank() && it.code == raw }
        val t = m.firstOrNull()
        val canUse = t != null && m.size == 1 && t.status == "Active"
        val (title, body) = when {
            t == null -> "Not found" to "No ticket in this app has the code \"$raw\"."
            m.size > 1 -> "Check manually" to "${m.size} tickets share this code."
            t.status == "Active" -> "Valid ticket" to describe(t)
            t.status == "Used" -> "Already used" to describe(t)
            else -> "Not valid (${t.status})" to describe(t)
        }
        AlertDialog(
            onDismissRequest = { scanRaw = null },
            title = { Text(title) },
            text = { Text(body) },
            confirmButton = {
                if (canUse && t != null) TextButton(onClick = { vm.save(t.copy(status = "Used")); scanRaw = null }) { Text("Mark as used") }
                else TextButton(onClick = { scanRaw = null }) { Text("OK") }
            },
            dismissButton = { if (canUse) TextButton(onClick = { scanRaw = null }) { Text("Close") } }
        )
    }
    toDelete?.let { t ->
        AlertDialog(
            onDismissRequest = { toDelete = null },
            title = { Text("Delete ticket?") },
            text = { Text("${t.firstName} ${t.lastName} – ${t.venue}. This cannot be undone.") },
            confirmButton = { TextButton(onClick = { vm.delete(t); toDelete = null }) { Text("Delete") } },
            dismissButton = { TextButton(onClick = { toDelete = null }) { Text("Cancel") } }
        )
    }
}

@Composable
fun CredentialsDialog(prefs: SharedPreferences, onClose: () -> Unit, onSaved: () -> Unit) {
    var id by remember { mutableStateOf(prefs.getString("client_id", "").orEmpty()) }
    var secret by remember { mutableStateOf(prefs.getString("client_secret", "").orEmpty()) }
    val valid = id.contains(".apps.googleusercontent.com") && secret.length >= 8 && !secret.contains(" ")
    AlertDialog(
        onDismissRequest = onClose,
        title = { Text("Google credentials") },
        text = {
            Column(Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("Enter the Client ID and Client secret of your own Google Cloud OAuth client " +
                    "(type: Desktop app). See GOOGLE-SETUP.md for the steps.")
                Field("Client ID", id) { id = it.trim() }
                OutlinedTextField(
                    value = secret, onValueChange = { secret = it.trim() }, label = { Text("Client secret") },
                    singleLine = true, visualTransformation = PasswordVisualTransformation(),
                    modifier = Modifier.fillMaxWidth()
                )
                if (GoogleAuth.signedIn(prefs)) {
                    TextButton(onClick = { GoogleAuth.signOut(prefs); onClose() }) { Text("Sign out of Google") }
                }
            }
        },
        confirmButton = {
            TextButton(enabled = valid, onClick = { GoogleAuth.saveClient(prefs, id, secret); onSaved() }) { Text("Save") }
        },
        dismissButton = { TextButton(onClick = onClose) { Text("Cancel") } }
    )
}

@Composable
fun TicketCard(t: Ticket, onEdit: () -> Unit, onDuplicate: () -> Unit, onCode: () -> Unit, onDelete: () -> Unit) {
    val dim = MaterialTheme.colorScheme.onSurfaceVariant
    val statusColor = when (t.status) {
        "Cancelled", "Refunded" -> MaterialTheme.colorScheme.error
        "Used" -> dim
        else -> MaterialTheme.colorScheme.primary
    }
    Card(Modifier.fillMaxWidth()) {
        Column(Modifier.padding(14.dp)) {
            Text("${t.firstName} ${t.lastName}".trim(), style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
            Text(listOf(t.venue, t.location).filter { it.isNotBlank() }.joinToString(" · "))
            Text(listOf(t.date, t.time, t.seat).filter { it.isNotBlank() }.joinToString(" · "), color = dim)
            Text("${t.venueType} · ${t.ticketType}", color = dim)
            if (t.notes.isNotBlank()) Text(t.notes, color = dim)
            Row(Modifier.fillMaxWidth().padding(top = 6.dp), verticalAlignment = Alignment.CenterVertically) {
                Text(money(t.price), fontWeight = FontWeight.SemiBold)
                Spacer(Modifier.weight(1f))
                Text(t.status, color = statusColor, fontWeight = FontWeight.SemiBold)
            }
            Row(Modifier.horizontalScroll(rememberScrollState())) {
                TextButton(onClick = onEdit) { Text("Edit") }
                TextButton(onClick = onDuplicate) { Text("Duplicate") }
                TextButton(onClick = onCode) { Text("Code") }
                TextButton(onClick = onDelete) { Text("Delete", color = MaterialTheme.colorScheme.error) }
            }
        }
    }
}

