// ---------- Data (stored only on this phone, in a local Room/SQLite database) ----------

@Entity(tableName = "tickets")
data class Ticket(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val firstName: String = "",
    val lastName: String = "",
    val venueType: String = "Concert",
    val ticketType: String = "Standard",
    val venue: String = "",
    val location: String = "",
    val date: String = "",
    val time: String = "",
    val seat: String = "",
    val price: Double = 0.0,
    val status: String = "Active",
    val notes: String = "",
    // Scanned from a real ticket, or generated by this app. Used by Scan to check a ticket.
    @ColumnInfo(defaultValue = "''") val code: String = "",
    // Sync: a unique id that is the same on every device, when it last changed, and a deleted flag.
    @ColumnInfo(defaultValue = "''") val uid: String = "",
    @ColumnInfo(defaultValue = "0") val updatedAt: Long = 0,
    @ColumnInfo(defaultValue = "0") val deleted: Boolean = false
)

@Dao
interface TicketDao {
    @Query("SELECT * FROM tickets WHERE deleted = 0 ORDER BY date, time")
    fun all(): Flow<List<Ticket>>
    @Query("SELECT * FROM tickets")
    suspend fun allWithDeleted(): List<Ticket>
    @Insert suspend fun insert(t: Ticket): Long
    @Update suspend fun update(t: Ticket)
    @Delete suspend fun delete(t: Ticket)
}

@Database(entities = [Ticket::class], version = 3, exportSchema = false)
abstract class AppDb : RoomDatabase() {
    abstract fun dao(): TicketDao
    companion object {
        @Volatile private var instance: AppDb? = null
        fun get(c: android.content.Context): AppDb = instance ?: synchronized(this) {
            instance ?: Room.databaseBuilder(c.applicationContext, AppDb::class.java, "tickets.db")
                .addMigrations(MIGRATION_1_2, MIGRATION_2_3).build().also { instance = it }
        }
    }
}

val MIGRATION_1_2 = object : Migration(1, 2) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE tickets ADD COLUMN code TEXT NOT NULL DEFAULT ''")
    }
}

val MIGRATION_2_3 = object : Migration(2, 3) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE tickets ADD COLUMN uid TEXT NOT NULL DEFAULT ''")
        db.execSQL("ALTER TABLE tickets ADD COLUMN updatedAt INTEGER NOT NULL DEFAULT 0")
        db.execSQL("ALTER TABLE tickets ADD COLUMN deleted INTEGER NOT NULL DEFAULT 0")
        db.execSQL("UPDATE tickets SET uid = lower(hex(randomblob(16))), updatedAt = CAST(strftime('%s','now') AS INTEGER) * 1000")
    }
}

class TicketVm(app: Application) : AndroidViewModel(app) {
    private val dao = AppDb.get(app).dao()
    val tickets = dao.all().stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), emptyList())
    fun save(t: Ticket) {
        viewModelScope.launch {
            val n = t.copy(updatedAt = System.currentTimeMillis(), uid = t.uid.ifBlank { java.util.UUID.randomUUID().toString() })
            if (n.id == 0L) dao.insert(n) else dao.update(n)
        }
    }
    fun saveAll(l: List<Ticket>) { viewModelScope.launch { l.forEach { dao.insert(it.copy(id = 0, uid = java.util.UUID.randomUUID().toString(), updatedAt = System.currentTimeMillis())) } } }
    // Deleting only marks the ticket as deleted, so the deletion can sync to other devices.
    fun delete(t: Ticket) { save(t.copy(deleted = true)) }

    fun sync(uri: Uri, onDone: (String) -> Unit) {
        viewModelScope.launch {
            val msg = try { withContext(Dispatchers.IO) { doSync(uri) } } catch (e: Exception) { "Sync failed: ${e.message}" }
            onDone(msg)
        }
    }

    fun syncDrive(token: String, onDone: (String) -> Unit) {
        viewModelScope.launch {
            val msg = try {
                withContext(Dispatchers.IO) {
                    val text = DriveApi.download(token) ?: ""
                    val (changed, out) = mergeRemote(text)
                    DriveApi.upload(token, out)
                    "Sync complete. $changed ticket(s) updated from Google Drive."
                }
            } catch (e: Exception) { "Sync failed: ${e.message}" }
            onDone(msg)
        }
    }

    private suspend fun doSync(uri: Uri): String {
        val cr = getApplication<Application>().contentResolver
        val text = cr.openInputStream(uri)?.bufferedReader()?.use { it.readText() }
            ?: throw IOException("Cannot open the sync file")
        if (text.length > 20_000_000) throw IOException("The sync file is too large")
        val (changed, out) = mergeRemote(text)
        cr.openOutputStream(uri, "wt")?.use { it.write(out.toByteArray()) }
            ?: throw IOException("Cannot write the sync file")
        return "Sync complete. $changed ticket(s) updated from the sync file."
    }

    /** Merges sync JSON (empty = nothing yet) into the database. Returns (updated count, merged JSON). */
    private suspend fun mergeRemote(text: String): Pair<Int, String> {
        val remote = if (text.isBlank()) emptyList() else parseSync(text)
        val result = dao.allWithDeleted().filter { it.uid.isNotBlank() }.associateBy { it.uid }.toMutableMap()
        var changed = 0
        for (r in remote) {
            val l = result[r.uid]
            if (l == null || r.updatedAt > l.updatedAt) {
                val t = r.copy(id = l?.id ?: 0)
                if (t.id == 0L) dao.insert(t) else dao.update(t)
                result[r.uid] = t
                changed++
            }
        }
        return changed to toSyncJson(result.values.sortedBy { it.uid })
    }
}

